// Regenerates src/abi.ts from the Foundry build output (run `arc-forge build` first).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const abiOf = (file: string, name: string) =>
  JSON.parse(readFileSync(new URL(`../contracts/out/${file}/${name}.json`, root), "utf8")).abi;

const out = `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit by hand.
export const verdictVaultAbi = ${JSON.stringify(abiOf("VerdictVault.sol", "VerdictVault"), null, 2)} as const;

export const guaranteeBookAbi = ${JSON.stringify(abiOf("GuaranteeBook.sol", "GuaranteeBook"), null, 2)} as const;

export const batchGuardAbi = ${JSON.stringify(abiOf("BatchGuard.sol", "BatchGuard"), null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL("src/abi.ts", root)), out);
console.log("wrote src/abi.ts");
