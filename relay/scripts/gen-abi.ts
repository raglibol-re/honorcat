// Regenerates src/abi.ts from the Foundry build output (run `arc-forge build` first).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const artifact = JSON.parse(
  readFileSync(new URL("../contracts/out/VerdictVault.sol/VerdictVault.json", root), "utf8"),
);
const out = `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit by hand.
export const verdictVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL("src/abi.ts", root)), out);
console.log("wrote src/abi.ts");
