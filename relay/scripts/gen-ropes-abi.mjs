// Writes src/ropesAbi.ts: HonorCatRopes' ABI merged with HonorCatRopesExtension's (the extension's
// functions are called at the HonorCatRopes address, which runs them by delegatecall).
// Run after `forge build` in contracts/: node scripts/gen-ropes-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
const out = (n, f) => JSON.parse(readFileSync(new URL(`../../contracts/out/${f}/${n}.json`, import.meta.url), "utf8")).abi;
const main = out("HonorCatRopes", "HonorCatRopes.sol");
const ext = out("HonorCatRopesExtension", "HonorCatRopesExtension.sol");
const key = (x) => `${x.type}:${x.name ?? ""}:${(x.inputs ?? []).map((i) => i.type).join(",")}`;
const seen = new Set(main.map(key));
const merged = [...main, ...ext.filter((x) => x.type !== "constructor" && x.type !== "fallback" && !seen.has(key(x)))];
writeFileSync(
  new URL("../src/ropesAbi.ts", import.meta.url),
  `// HonorCatRopes (v2) ABI merged with HonorCatRopesExtension's functions, which run at the same address.\n// Generated by scripts/gen-ropes-abi.mjs from contracts/out. Do not edit by hand.\nexport const ropesAbi = ${JSON.stringify(merged, null, 2)} as const;\n`,
);
console.log(`ropesAbi: ${merged.length} entries (${main.length} main, ${merged.length - main.length} from the extension)`);
