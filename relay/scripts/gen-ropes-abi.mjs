// Writes src/ropesAbi.ts: HonorCatRopes' ABI merged with HonorCatRopesExtension's and HonorCatRopesExtra's
// (their functions are called at the HonorCatRopes address, which runs them by delegatecall), and
// src/perpsAbi.ts (HonorCatPerps).
// Run after `forge build` in contracts/: node scripts/gen-ropes-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
const out = (n, f) => JSON.parse(readFileSync(new URL(`../../contracts/out/${f}/${n}.json`, import.meta.url), "utf8")).abi;
const main = out("HonorCatRopes", "HonorCatRopes.sol");
const ext = out("HonorCatRopesExtension", "HonorCatRopesExtension.sol");
const extra = out("HonorCatRopesExtra", "HonorCatRopesExtra.sol");
const key = (x) => `${x.type}:${x.name ?? ""}:${(x.inputs ?? []).map((i) => i.type).join(",")}`;
const seen = new Set(main.map(key));
const merged = [...main];
for (const x of [...ext, ...extra]) {
  if (x.type === "constructor" || x.type === "fallback" || seen.has(key(x))) continue;
  seen.add(key(x));
  merged.push(x);
}
writeFileSync(
  new URL("../src/ropesAbi.ts", import.meta.url),
  `// HonorCatRopes (v2) ABI merged with HonorCatRopesExtension's functions, which run at the same address.\n// Generated by scripts/gen-ropes-abi.mjs from contracts/out. Do not edit by hand.\nexport const ropesAbi = ${JSON.stringify(merged, null, 2)} as const;\n`,
);
console.log(`ropesAbi: ${merged.length} entries (${main.length} main, ${merged.length - main.length} from the extension)`);

const perps = out("HonorCatPerps", "HonorCatPerps.sol");
writeFileSync(
  new URL("../src/perpsAbi.ts", import.meta.url),
  `// HonorCatPerps ABI. Generated by scripts/gen-ropes-abi.mjs from contracts/out. Do not edit by hand.
export const perpsAbi = ${JSON.stringify(perps, null, 2)} as const;
`,
);
console.log(`perpsAbi: ${perps.length} entries`);
